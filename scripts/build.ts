// Builds mods/<name>/main.js from src/entries/*.ts and checks the output (plan §1 ビルド, spike S1).
//   bun run scripts/build.ts
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LAYOUT_NAME, MOD_EDITOR, MOD_FILES, MOD_OPEN, MOD_UNINSTALL, isValidModName } from "../src/core/names";

const HOST = ["herdr", "gpui-kit", "gpui-base", "fs/promises"];
const ROOT = join(import.meta.dir, "..");

interface ModSpec {
  name: string;
  entry: string;
  manifest: Record<string, unknown>;
  assets?: [string, string][];
  /** Copy the entry's leading `//` comment into main.js. Bundling drops comments, and Apache-2.0
   *  §4(b) needs the notice that a modified file was changed in the file people receive. */
  keepHeader?: boolean;
}

function leadingComment(source: string): string {
  const lines: string[] = [];
  for (const line of source.split("\n")) {
    if (!line.startsWith("//")) break;
    lines.push(line);
  }
  return lines.length ? lines.join("\n") + "\n" : "";
}

const mods: ModSpec[] = [
  { name: MOD_EDITOR, entry: "src/entries/editor.ts", manifest: { place: "none", focusable: true } },
  {
    name: MOD_OPEN,
    entry: "src/entries/editor-open.ts",
    manifest: {
      place: "none",
      focusable: true,
      overlay: { kind: "popup", at: "top", offset: 40, width: 640, height: 0.6 },
    },
  },
  {
    name: MOD_UNINSTALL,
    entry: "src/entries/editor-uninstall.ts",
    manifest: { place: "none", overlay: { width: 520, height: 260 } },
  },
  {
    name: MOD_FILES,
    entry: "src/entries/editor-files.js",
    manifest: { place: "none" },
    keepHeader: true,
    assets: ["chevron-down.svg", "chevron-right.svg", "file.svg", "folder.svg", "LICENSE", "LICENSE-Lucide.txt"].map(
      (f) => [`vendor/herdr-files/${f}`, f],
    ),
  },
];

function checkOutput(name: string, code: string): string[] {
  const problems: string[] = [];
  if (code.startsWith("// @bun")) problems.push("starts with the // @bun pragma (use --target node)");
  for (const m of code.matchAll(/^import\s[^;]*?from\s+"([^"]+)"/gm)) {
    if (!HOST.includes(m[1]!)) problems.push(`unexpected import "${m[1]}"`);
  }
  if (/\bimport\s*\(/.test(code)) problems.push("dynamic import()");
  if (/\b(setTimeout|setInterval)\s*\(/.test(code)) problems.push("setTimeout/setInterval (use cx.timer)");
  if (/var \w+ = \(\(\) => \(\{\}\)\);/.test(code)) problems.push("a host module was replaced by an empty stub (S1-2)");
  return problems.map((p) => `${name}: ${p}`);
}

let failed: string[] = [];
for (const mod of mods) {
  if (!isValidModName(mod.name)) {
    failed.push(`invalid mod name ${mod.name}`);
    continue;
  }
  const out = join(ROOT, "mods", mod.name);
  mkdirSync(out, { recursive: true });
  const result = await Bun.build({
    entrypoints: [join(ROOT, mod.entry)],
    target: "node",
    format: "esm",
    external: HOST,
    minify: false,
  });
  if (!result.success) {
    failed.push(...result.logs.map((l) => `${mod.name}: ${l.message}`));
    continue;
  }
  const code = await result.outputs[0]!.text();
  failed.push(...checkOutput(mod.name, code));
  let header = "";
  if (mod.keepHeader) {
    header = leadingComment(readFileSync(join(ROOT, mod.entry), "utf8"));
    if (!header.includes("Modified from")) failed.push(`${mod.name}: ${mod.entry} has no "Modified from" notice`);
    header += "//\n";
  }
  writeFileSync(
    join(out, "main.js"),
    `${header}// Generated by scripts/build.ts from ${mod.entry}. Do not edit.\n${code}`,
  );
  writeFileSync(join(out, "mod.json"), JSON.stringify(mod.manifest, null, 2) + "\n");
  for (const [from, to] of mod.assets ?? []) cpSync(join(ROOT, from), join(out, to));
}

// layouts/<LAYOUT_NAME>.json: Herdr's main layout with the Files block pointing at the fork.
{
  const layout = JSON.parse(readFileSync(join(ROOT, "vendor/herdr-layouts/main.json"), "utf8"));
  let replaced = 0;
  const walk = (n: unknown): void => {
    if (Array.isArray(n)) {
      n.forEach(walk);
      return;
    }
    if (!n || typeof n !== "object") return;
    const o = n as Record<string, unknown>;
    const c = o.content as { mod?: string } | undefined;
    if (c && c.mod === "files") {
      c.mod = MOD_FILES;
      replaced++;
    }
    Object.values(o).forEach(walk);
  };
  walk(layout);
  if (replaced !== 1) failed.push(`layout: expected one Files block, found ${replaced}`);
  layout.cloned_from = { name: "main", version: "0.1.16 (identical in 0.1.15 and herdr-app 5216e6f)" };
  mkdirSync(join(ROOT, "layouts"), { recursive: true });
  writeFileSync(join(ROOT, "layouts", `${LAYOUT_NAME}.json`), JSON.stringify(layout, null, 2) + "\n");
}

if (failed.length) {
  console.error(failed.join("\n"));
  process.exit(1);
}
console.log(`built ${mods.map((m) => `mods/${m.name}`).join(", ")}, layouts/${LAYOUT_NAME}.json`);
